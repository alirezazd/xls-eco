ABSL_FLAG(std::string, input_ir_path, "", "Path to the IR file to patch.");
ABSL_FLAG(std::string, input_patch_path, "", "Path to the patch file.");
ABSL_FLAG(std::string, output_ir_path, "", "Path to the patched IR file.");
ABSL_FLAG(std::string, input_schedule_path, "",
          "PackageScheduleProto textproto of the input IR. When given, the "
          "patched IR is rescheduled keeping every original cycle assignment "
          "that stays feasible.");
ABSL_FLAG(
    std::string, input_schedule_ir_path, "",
    "IR file the schedule names (codegen_main --output_schedule_ir_path). "
    "The patched IR is aligned with it after the scheduling passes, so "
    "the nodes those passes create are pinned as well.");
ABSL_FLAG(std::string, output_schedule_report_path, "",
          "Where to write what the patch did to the schedule: nodes matched, "
          "clock, stages, assignments kept.");
